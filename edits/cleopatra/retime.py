#!/usr/bin/env python3
"""v1 timeline -> v2 narration: anchors every caption chunk (segs_v1.txt -> segs.txt) and writes web/retime.js
(toOld(newFrame) for the renderer) + retime.json (for subs.py / audio.py)."""
import json
old = [tuple(map(float, l.split())) for l in open('segs_v1.txt')]; new = [tuple(map(float, l.split())) for l in open('segs.txt')]
END_OLD, TAIL = 60.0, 3.25
END_NEW = round((new[-1][1] + TAIL) * 30) / 30
anch = [(0.0, 0.0)]
for i, ((oa, ob), (na, nb)) in enumerate(zip(old, new)):
    if i != 13: anch.append((oa, na))   # chunk 12/13 boundary moved ("Then Cleopatra | the Seventh…" -> "…the Seventh | is born")
    if i != 12: anch.append((ob, nb))
anch.append((END_OLD, END_NEW)); anch = sorted(set(anch))
assert all(b[0] > a[0] and b[1] > a[1] for a, b in zip(anch, anch[1:]))
TOT = int(round(END_NEW * 30))
js = "// generated by retime.py: v1 timeline (old frames) -> v2 narration (new frames)\nexport const TMAP = %s;\nexport const TOTAL_NEW = %d;\n" % (str([[round(o * 30, 2), round(n * 30, 2)] for o, n in anch]), TOT)
js += """/** new frame -> old (v1) frame, piecewise linear between caption anchors */
export const toOld = (f) => { const M = TMAP; if (f <= M[0][1]) return M[0][0]; for (let i = 1; i < M.length; i++) if (f <= M[i][1]) { const [o0, n0] = M[i - 1], [o1, n1] = M[i]; return o0 + (o1 - o0) * (f - n0) / (n1 - n0); } return M[M.length - 1][0]; };
"""
open('web/retime.js', 'w').write(js)
json.dump({'map': [[o * 30, n * 30] for o, n in anch], 'total': TOT}, open('retime.json', 'w'))
print('TOTAL_NEW', TOT, 'END', END_NEW, 'anchors', len(anch))
